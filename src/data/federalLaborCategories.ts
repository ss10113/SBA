export interface LaborCategoryBenchmark {
  id: string;
  socCode: string; // Standard Occupational Classification or DOL SCA code
  scaCode?: string; // DOL SCA Directory of Occupations code if applicable
  title: string;
  category: 'Information Technology' | 'Cybersecurity' | 'Engineering' | 'Program Management' | 'Professional & Business' | 'Logistics' | 'Administrative' | 'Healthcare';
  exemptionStatus: 'Exempt (FLSA)' | 'Non-Exempt (SCA Covered)';
  minRate: number; // Floor / 25th percentile ($/hr fully burdened)
  medianRate: number; // Target / 50th percentile ($/hr fully burdened)
  maxRate: number; // Ceiling / 90th percentile ($/hr fully burdened)
  scaWageFloor?: number; // Mandatory DOL statutory direct hourly wage floor
  healthAndWelfare?: number; // Mandatory fringe benefit (default $5.36/hr for SCA)
  education: 'High School' | 'Associate' | 'Bachelor' | 'Master' | 'Doctorate';
  minYearsExp: number;
  certifications: string[];
  clearanceLevel: 'None / Public Trust' | 'Public Trust' | 'Secret' | 'Top Secret' | 'TS/SCI' | 'Secret / IT-II' | 'None';
  description: string;
  typicalClinDeliverables: string[];
  gsaScheduleSource?: string;
}

